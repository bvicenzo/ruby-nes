# frozen_string_literal: true

module Ruby
  module Nes
    module Debug
      # A frame as a binary PPM image (https://netpbm.sourceforge.net/doc/ppm.html), for looking at what the PPU drew:
      # "P6", the width, the height and the maximum colour value, then each pixel's red, green and blue bytes, row by
      # row. Debug tooling, off the hot path; turning indices into colours is otherwise the frontends' job
      # (docs/architecture.md, Frame buffer contract).
      class FrameDump
        # NESdev's 2C02G_U_wiki.pal (https://www.nesdev.org/wiki/File:2C02G_U_wiki.pal): "A palette generated by Pally
        # v0.23.0" (pally.py --skip-plot -cld -phd 4 -e -blp 7.5), generator "licensed under MIT-0"; the wiki's
        # content "is considered public domain" (https://www.nesdev.org/wiki/Nesdev_wiki:General_disclaimer). The file
        # holds the 64 colours for each of the 8 emphasis combinations; these are the first 64, without emphasis, taken
        # from the generator's copy of the same file (https://github.com/Gumball2415/pally, docs/NESDev) because the
        # wiki refuses scripted downloads. Red, green and blue of each palette index, as hexadecimal.
        PALETTE = <<~COLOURS.split.map { [it].pack('H*').bytes.freeze }.freeze
          575757 000C8E 0800A6 340096 550061 630015 5A0000 3C0E00
          112800 003B00 004200 003A05 002652 000000 000000 000000
          A5A5A5 0041D9 2F1EFF 6704F2 9400B4 AA0057 A31800 803900
          4B5B00 137600 008100 007923 006288 000000 000000 000000
          FFFFFF 4A9FFF 797EFF AF63FF DD55FF F757C2 F76A63 DC8810
          AEA900 78C400 4AD211 2FCF64 2FBDC4 414141 000000 000000
          FFFFFF B9DDFF CAD1FF DEC6FF F0C0FF FCC0EE FDC6CA F5D0AA
          E4DD95 D0E892 BDEEA2 B2EEC0 B0E8E3 B3B3B3 000000 000000
        COLOURS
        MAXIMUM_COLOUR_VALUE = 255
        HEADER = "P6\n#{Ppu::Picture::WIDTH} #{Ppu::Picture::HEIGHT}\n#{MAXIMUM_COLOUR_VALUE}\n".freeze

        # The PPM image of a frame buffer of palette indices; an index outside 0-63 raises IndexError.
        def self.ppm(frame_buffer)
          HEADER + frame_buffer.flat_map { PALETTE.fetch(it) }.pack('C*')
        end
      end
    end
  end
end
